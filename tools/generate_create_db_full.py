def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        description="Generate create_db_full.py by embedding schema_from_working_db.sql."
    )
    p.add_argument(
        "--schema",
        default=str(DEFAULT_SCHEMA_PATH),
        help="Path to schema SQL file (default: ./schema_from_working_db.sql)",
    )
    p.add_argument(
        "--out",
        default=str(DEFAULT_OUT_PATH),
        help="Output path for create_db_full.py (default: ./create_db_full.py)",
    )
    p.add_argument(
        "--no-sanitize",
        action="store_true",
        help="Do not strip sqlite_sequence statements (NOT recommended).",
    )
    args = p.parse_args(argv)

    schema_path = Path(args.schema).resolve()
    out_path = Path(args.out).resolve()

    if not schema_path.exists():
        raise SystemExit(f"Schema file not found: {schema_path}")

    raw = schema_path.read_text(encoding="utf-8")
    if "CREATE TABLE" not in raw.upper():
        raise SystemExit(f"Schema file doesn't look like DDL: {schema_path}")

    sql = raw
    if not args.no_sanitize:
        sql = sanitize_schema_sql(sql)

    rendered = render_create_db_full(sql, str(schema_path))
    out_path.write_text(rendered, encoding="utf-8")

    # Make it obvious where it landed
    print(f"✅ Wrote: {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

