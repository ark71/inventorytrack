#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
from datetime import datetime
from pathlib import Path


DEFAULT_SCHEMA_PATH = Path("schema_from_working_db.sql")
DEFAULT_OUT_PATH = Path("create_db_full.py")


def sanitize_schema_sql(sql: str) -> str:
    """
    Strip statements that reference sqlite_sequence (SQLite internal AUTOINCREMENT table).
    Some exports include:
      CREATE TABLE sqlite_sequence(name,seq);
      INSERT INTO sqlite_sequence VALUES(...);
    Those are not replayable and will error on executescript().
    """
    out_lines: list[str] = []
    skipping_stmt = False

    for line in sql.splitlines(True):
        if not skipping_stmt and re.search(r"\bsqlite_sequence\b", line, flags=re.IGNORECASE):
            # Drop this line; if statement continues, keep skipping until ';'
            if ";" not in line:
                skipping_stmt = True
            continue

        if skipping_stmt:
            if ";" in line:
                skipping_stmt = False
            continue

        out_lines.append(line)

    return "".join(out_lines)


def _strip_trailing_whitespace_preserve_newline(s: str) -> str:
    lines = s.splitlines()
    lines = [ln.rstrip() for ln in lines]
    return "\n".join(lines).rstrip() + "\n"


def render_create_db_full(schema_sql: str, schema_source: str) -> str:
    # Use triple single quotes so double quotes inside SQL don't need escaping.
    # Keep SQL as-is (post-sanitization) to preserve exact DDL/indexes.
    schema_sql = _strip_trailing_whitespace_preserve_newline(schema_sql)

    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

